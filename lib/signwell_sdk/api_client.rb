    def basic_auth(conn)
      if config.username && config.password
        if Gem::Version.new(Faraday::VERSION) >= Gem::Version.new('2.0')
          conn.request(:authorization, :basic, config.username, config.password)
        else
          conn.request(:basic_auth, config.username, config.password)
        end
      end
    end

    # Check if the given MIME is a JSON MIME.
    # JSON MIME examples:
    #   application/json
    #   application/json; charset=UTF8
    #   APPLICATION/JSON
    #   */*
    # @param [String] mime MIME
    # @return [Boolean] True if the MIME is application/json
    def json_mime?(mime)
      (mime == '*/*') || !(mime =~ /^Application\/.*json(?!p)(;.*)?/i).nil?
    end

    def normalize_content_type(content_type)
      return nil if content_type.nil?

      normalized = content_type.to_s.split(';').first&.strip
      normalized.nil? || normalized.empty? ? nil : normalized
    end

    def normalize_query_params(query_params)
      query_params.each_with_object({}) do |(key, value), normalized|
        key_string = key.to_s

        if key_string.end_with?('[]') && value.is_a?(Array)
          normalized[key_string.delete_suffix('[]')] = value
        else
          normalized[key] = value
        end
      end
    end

    def resolve_return_type(response, return_type)
      return return_type unless return_type.is_a?(Hash)

      content_type = normalize_content_type(response.headers['Content-Type'])
      return return_type[content_type] if content_type && return_type.key?(content_type)
      return return_type['default'] if return_type.key?('default')

      raise Errors::UnsupportedContentTypeError.new(
        message: "Content-Type is not supported for this operation: #{response.headers['Content-Type']}",
        response_headers: response.headers,
        response_body: response.body
      )
    end

    def streamed_response?(return_type)
      case return_type
      when 'File', 'Binary'
        true
      when Hash
        %w(File Binary).include?(return_type['default'])
      else
        false
      end
    end

    def build_transport_error_message(prefix, error, operation: nil)
      message = error.message.to_s.strip
      context = operation || 'API request'
      return "#{prefix} while calling #{context}" if message.empty?

      "#{prefix} while calling #{context}: #{message}"
    end

    # Deserialize the response to the given return type.
    #
    # @param [Response] response HTTP response
    # @param [String] return_type some examples: "User", "Array<User>", "Hash<String, Integer>"
    def deserialize(response, return_type)
      body = response.body
      return nil if body.nil? || body.empty?

      # return response body directly for String return type
      return body.to_s if return_type == 'String'

      # ensuring a default content type
      content_type = normalize_content_type(response.headers['Content-Type']) || 'application/json'

      unless json_mime?(content_type)
        raise Errors::UnsupportedContentTypeError.new(
          message: "Content-Type is not supported: #{content_type}",
          response_headers: response.headers,
          response_body: body
        )
      end

      begin
        data = JSON.parse("[#{body}]", :symbolize_names => true)[0]
      rescue JSON::ParserError => e
        if %w(String Date Time).include?(return_type)
          data = body
        else
          raise e
        end
      end

      convert_to_type data, return_type
    end

    # Convert data to the given return type.
    # @param [Object] data Data to be converted
    # @param [String] return_type Return type
    # @return [Mixed] Data in a particular type
    def convert_to_type(data, return_type)
      return nil if data.nil?
      case return_type
      when 'String'
        data.to_s
      when 'Integer'
        data.to_i
      when 'Float'
        data.to_f
      when 'Boolean'
        data == true
      when 'Time'
        # parse date time (expecting ISO 8601 format)
        Time.parse data
      when 'Date'
        # parse date time (expecting ISO 8601 format)
        Date.parse data
      when 'Object'
        # generic object (usually a Hash), return directly
        data
      when /\AArray<(.+)>\z/
        # e.g. Array<Pet>
        sub_type = $1
        data.map { |item| convert_to_type(item, sub_type) }
      when /\AHash\<String, (.+)\>\z/
        # e.g. Hash<String, Integer>
        sub_type = $1
        {}.tap do |hash|
          data.each { |k, v| hash[k] = convert_to_type(v, sub_type) }
        end
      else
        # models (e.g. Pet) or oneOf
        klass = SignWell::Models.const_get(return_type)
        klass.respond_to?(:openapi_one_of) ? klass.build(data) : klass.build_from_hash(data)
      end
    end

    # Sanitize filename by removing path.
    # e.g. ../../sun.gif becomes sun.gif
    #
    # @param [String] filename the filename to be sanitized
    # @return [String] the sanitized filename
    def sanitize_filename(filename)
      filename.split(/[\/\\]/).last
    end

    def build_request_url(path, opts = {})
      # Add leading and trailing slashes to path
      path = "/#{path}".gsub(/\/+/, '/')
      @config.base_url(opts[:operation]) + path
    end

    # Update header and query params based on authentication settings.
    #
    # @param [Hash] header_params Header parameters
    # @param [Hash] query_params Query parameters
    # @param [String] auth_names Authentication scheme name
    def update_params_for_auth!(header_params, query_params, auth_names)
      Array(auth_names).each do |auth_name|
        auth_setting = @config.auth_settings[auth_name]
        next unless auth_setting
        case auth_setting[:in]
        when 'header' then header_params[auth_setting[:key]] = auth_setting[:value]
        when 'query'  then query_params[auth_setting[:key]] = auth_setting[:value]
        else fail ArgumentError, 'Authentication token must be in `query` or `header`'
        end
      end
    end

