    # Builds the HTTP request
    #
    # @param [String] http_method HTTP method/verb (e.g. POST)
    # @param [String] path URL path (e.g. /account/new)
    # @option opts [Hash] :header_params Header parameters
    # @option opts [Hash] :query_params Query parameters
    # @option opts [Hash] :form_params Query parameters
    # @option opts [Object] :body HTTP body (JSON/XML)
    # @return [Faraday::Request] A Faraday Request
    def build_request(http_method, path, request, opts = {})
      url = build_request_url(path, opts)
      http_method = http_method.to_sym.downcase

      header_params = @default_headers.merge(opts[:header_params] || {})
      query_params = opts[:query_params] || {}
      form_params = opts[:form_params] || {}

      update_params_for_auth! header_params, query_params, opts[:auth_names]

      if [:post, :patch, :put, :delete].include?(http_method)
        req_body = build_request_body(header_params, form_params, opts[:body])
        if config.debugging
          config.logger.debug "HTTP request body param ~BEGIN~\n#{req_body}\n~END~\n"
        end
      end
      request.headers = header_params
      request.body = req_body

      # Overload default options only if provided
      request.options.params_encoder = config.params_encoder if config.params_encoder
      request.options.timeout        = config.timeout        if config.timeout

      request.url url
      request.params = normalize_query_params(query_params)
      request
    end

    # Builds the HTTP request body
    #
    # @param [Hash] header_params Header parameters
    # @param [Hash] form_params Query parameters
    # @param [Object] body HTTP body (JSON/XML)
    # @return [String] HTTP body data in the form of string
    def build_request_body(header_params, form_params, body)
      # http form
      if header_params['Content-Type'] == 'application/x-www-form-urlencoded'
        data = URI.encode_www_form(form_params)
      elsif header_params['Content-Type'] == 'multipart/form-data'
        data = {}
        form_params.each do |key, value|
          case value
          when ::File, ::Tempfile
            data[key] = Faraday::FilePart.new(value.path, Marcel::MimeType.for(Pathname.new(value.path)))
          when ::Array, nil
            # let Faraday handle Array and nil parameters
            data[key] = value
          else
            data[key] = value.to_s
          end
        end
      elsif body
        data = body.is_a?(String) ? body : body.to_json
      else
        data = nil
      end
      data
    end

    def download_file(request)
      stream = if @config.return_binary_data == true
                 +""
               else
                 tempfile = Tempfile.open('download-', @config.temp_folder_path)
                 tempfile.binmode
                 tempfile
               end

      # handle streaming Responses
      request.options.on_data = Proc.new do |chunk, _overall_received_bytes|
        if stream.is_a?(Tempfile)
          stream.write(chunk)
        else
          stream << chunk
        end
      end

      stream
    end

    def deserialize_file(response, stream)
      return deserialize_streamed_file(response, stream) if stream.is_a?(Tempfile)

      content = stream.to_s
      content = decode_binary_transfer(content) if binary_transfer_encoded?(response)

      if @config.return_binary_data == true
        encoding = response.body.respond_to?(:encoding) ? response.body.encoding : Encoding::BINARY
        return content.force_encoding(encoding)
      end

      tempfile = build_download_tempfile(response)
      tempfile.binmode
      tempfile.write(content)
      tempfile.close
      log_download_path(tempfile.path)
      tempfile
    end

    # Streamed downloads keep the fixed +download-+ prefix, decoded or not. The streamed
    # tempfile is opened before the first byte arrives, and the decoded one must not take the
    # Content-Disposition name either: a long filename plus Tempfile's own suffix overflows
    # NAME_MAX (255 bytes) and Tempfile.open raises Errno::ENAMETOOLONG. Do not try to rename
    # it later: File.rename leaves Tempfile#path pointing at nothing and the renamed file
    # surviving close!. Callers who need the real name should read Content-Disposition from
    # the *_with_http_info variants.
    def deserialize_streamed_file(response, stream)
      stream.flush
      stream.rewind
      downloaded = maybe_decode_binary_transfer_to_tempfile(response, stream)

      begin
        downloaded.close
        log_download_path(downloaded.path)
      rescue StandardError
        discard_download_stream(downloaded)
        raise
      end

      downloaded
    end

    def build_download_tempfile(response)
      content_disposition = response.headers['Content-Disposition']
      if content_disposition && content_disposition =~ /filename=/i
        filename = content_disposition[/filename=['"]?([^'"\s]+)['"]?/, 1]
        prefix = sanitize_filename(filename)
      else
        prefix = 'download-'
      end
      prefix += '-' unless prefix.end_with?('-')

      Tempfile.open(prefix, @config.temp_folder_path)
    end

    def maybe_decode_binary_transfer_to_tempfile(response, stream)
      return stream unless binary_transfer_encoded?(response)

      # Fixed prefix on purpose; see deserialize_streamed_file.
      decoded = Tempfile.open('download-', @config.temp_folder_path)

      begin
        decoded.binmode
        decode_binary_transfer_stream(stream, decoded)
        decoded.flush
        decoded.rewind
      rescue StandardError
        # call_api unlinks +stream+; nothing else knows this file exists yet.
        discard_download_stream(decoded)
        raise
      end

      stream.close!
      decoded
    end

    def binary_transfer_encoded?(response)
      %w(binary base64).include?(response.headers['Content-Transfer-Encoding'].to_s.downcase)
    end

    def decode_binary_transfer(content)
      content.unpack('m').join
    end

    def decode_binary_transfer_stream(source, destination)
      pending = +""
      while (chunk = source.read(64 * 1024))
        pending << chunk.gsub(/\s+/, '')
        decode_length = pending.length - (pending.length % 4)
        next if decode_length.zero?

        destination.write(decode_binary_transfer(pending.slice!(0, decode_length)))
      end

      destination.write(decode_binary_transfer(pending)) unless pending.empty?
    end

    def log_download_path(path)
      config.logger.info "Temp file written to #{path}, please copy the file to a proper folder "\
                         "with e.g. `FileUtils.cp(tempfile.path, '/new/file/path')` otherwise the temp file "\
                         "will be deleted automatically with GC. It's also recommended to delete the temp file "\
                         "explicitly with `tempfile.delete`"
    end

    def connection(opts)
      opts[:header_params]['Content-Type'] == 'multipart/form-data' ? connection_multipart : connection_regular
    end

