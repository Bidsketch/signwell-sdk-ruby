    # @return [Array<(Object, Integer, Hash)>] an array of 3 elements:
    #   the data deserialized from response body (could be nil), response status code and response headers.
    def call_api(http_method, path, opts = {})
      stream = nil
      begin
        response = connection(opts).public_send(http_method.to_sym.downcase) do |req|
          request = build_request(http_method, path, req, opts)
          stream = download_file(request) if streamed_response?(opts[:return_type])
        end

        if config.debugging
          config.logger.debug "HTTP response body ~BEGIN~\n#{response.body}\n~END~\n"
        end

        unless response.success?
          if response.status == 0 && response.respond_to?(:return_message)
            # Errors from libcurl will be made visible here
            fail Errors::ApiError.new(code: 0,
                              message: response.return_message)
          else
            fail Errors::ApiStatusError.for(
              code: response.status,
              response_headers: response.headers,
              response_body: response.body,
              message: response.reason_phrase
            )
          end
        end
      rescue Faraday::TimeoutError => e
        raise Errors::ApiTimeoutError.new(
          message: build_transport_error_message('Connection timed out', e, operation: opts[:operation])
        ), cause: e
      rescue Faraday::ConnectionFailed => e
        raise Errors::ApiConnectionError.new(
          message: build_transport_error_message('Connection failed', e, operation: opts[:operation])
        ), cause: e
      end

      resolved_return_type = resolve_return_type(response, opts[:return_type])

      if resolved_return_type == 'File' || resolved_return_type == 'Binary'
        stream ||= response.body
        data = deserialize_file(response, stream)
      elsif resolved_return_type
        data = deserialize(response, resolved_return_type)
      else
        data = nil
      end
